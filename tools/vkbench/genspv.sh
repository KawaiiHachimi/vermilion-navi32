#!/bin/sh
# SPDX-License-Identifier: MIT
# genspv.sh: compile tools/vkbench/*.comp into tools/vkbench/vkbench_spv.h (checked in, so building vkbench needs
# no shader compiler). Needs glslang (`glslang` or `glslangValidator`, Khronos release 16.x) on PATH or in $GLSLANG.
set -eu
cd "$(dirname "$0")"
G=${GLSLANG:-$(command -v glslang || command -v glslangValidator)}
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
"$G" -V --target-env vulkan1.1 --vn spv_mandel -o "$tmp/m.h" mandel.comp >/dev/null
"$G" -V --target-env vulkan1.1 --vn spv_stream -o "$tmp/s.h" stream.comp >/dev/null
{ echo "// SPDX-License-Identifier: MIT"
  echo "// Generated by tools/vkbench/genspv.sh from mandel.comp and stream.comp ($("$G" --version | head -1)). Don't edit."
  cat "$tmp/m.h" "$tmp/s.h"; } > vkbench_spv.h
echo "wrote $(pwd)/vkbench_spv.h"
