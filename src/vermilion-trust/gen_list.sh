#!/bin/sh
# SPDX-License-Identifier: MIT
# gen_list.sh: writes phxtrust_list.inc, the cdhashes VermilionTrust lets through library validation.
# Usage: ./gen_list.sh [file ...]   (default: the Vermilion code installed in /Library/GPUBundles)
# Each file must be a thin x86_64 Mach-O with an embedded (ad-hoc) signature. Rebuild the kext after every install
# of the plugin, translator, RADV or decoder: a new build has a new cdhash, and AMFI refuses what isn't listed.
# PHXTRUST_KEEP=1 also keeps the cdhashes of the current phxtrust_list.inc, so one kext accepts the installed build and
# the next one: the plugin install and the EFI update then don't have to land in the same boot. Without it the list
# is exactly the files given.
# PHXTRUST_ADD="file ..." adds files that are not installed yet (the VideoToolbox bundle on the system volume, which
# appears only after the reboot that boots its snapshot), to the default list or to the files given.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
OUT="$HERE/phxtrust_list.inc"
if [ $# -eq 0 ]; then
  set -- /Library/GPUBundles/NVMTLDriver.bundle/Contents/MacOS/NVMTLDriver \
         /Library/GPUBundles/NVMTLDriver.bundle/Contents/MacOS/libnvmtl_translate.dylib \
         /Library/GPUBundles/NVMTLDriver.bundle/Contents/MacOS/air-runtime/libLLVM.dylib \
         /Library/GPUBundles/NVMTLDriver.bundle/Contents/MacOS/air-runtime/libzstd.1.dylib \
         /Library/GPUBundles/nvmtl/libvulkan_radeon.dylib
  # the optional video decoder (INSTALL.md 5.5): its dylibs next to the plugin, its VideoToolbox bundle on the system
  # volume (VTDecoderXPCService and the clients that load it are platform binaries)
  M=/Library/GPUBundles/NVMTLDriver.bundle/Contents/MacOS
  for f in $M/libphxdec_hevc.dylib $M/libavcodec_phx.61.dylib $M/libavutil_phx.59.dylib \
           /System/Library/Video/Plug-Ins/PhxVideoDecoder.bundle/Contents/MacOS/PhxVideoDecoder; do
    [ -f "$f" ] && set -- "$@" "$f"
  done
fi
for f in ${PHXTRUST_ADD:-}; do
  set -- "$@" "$f"
done
tmp=$(mktemp)
n=0
for f in "$@"; do
  [ -f "$f" ] || { echo "gen_list: $f: not found" >&2; rm -f "$tmp"; exit 1; }
  [ "$(lipo -archs "$f" 2>/dev/null)" = x86_64 ] || { echo "gen_list: $f: not a thin x86_64 Mach-O" >&2; rm -f "$tmp"; exit 1; }
  cd=$(codesign -dvvv "$f" 2>&1 | sed -n 's/^CDHash=//p')
  [ ${#cd} -eq 40 ] || { echo "gen_list: $f: no cdhash (unsigned?)" >&2; rm -f "$tmp"; exit 1; }
  printf '%s %s\n' "$cd" "$(basename "$f")" >>"$tmp"
  n=$((n + 1))
done
if [ "${PHXTRUST_KEEP:-0}" = 1 ] && [ -f "$OUT" ]; then
  for cd in $(sed -n 's/^[[:space:]]*{\(0x[^}]*\)},.*/\1/p' "$OUT" | sed 's/0x//g; s/, //g'); do
    grep -q "^$cd " "$tmp" && continue
    name=$(grep -F "$(echo "$cd" | sed -E 's/(..)/0x\1, /g; s/, $//')" "$OUT" | sed -n 's/.*}, \/\/ \([^ ]*\).*/\1/p' | head -n 1)
    while [ "${name%-previous}" != "$name" ]; do name=${name%-previous}; done; printf '%s %s\n' "$cd" "${name:-unknown}-previous" >>"$tmp"
    n=$((n + 1))
  done
fi
{
  echo "// Generated by gen_list.sh on $(date -u '+%Y-%m-%d %H:%M UTC'). Do not edit."
  echo "static const uint8_t kPhxTrustList[][20] = {"
  while read -r cd name; do
    printf '\t{'; echo "$cd" | sed -E 's/(..)/0x\1, /g; s/, $//' | tr -d '\n'; printf '}, // %s\n' "$name"
  done <"$tmp"
  echo "};"
  echo "static const char *const kPhxTrustNames[] = {"
  while read -r cd name; do printf '\t"%s",\n' "$name"; done <"$tmp"
  echo "};"
  echo "static constexpr size_t kPhxTrustCount = $n;"
} >"$OUT"
rm -f "$tmp"
echo "gen_list: $n cdhashes -> $OUT"
